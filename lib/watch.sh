# shellcheck shell=bash
# Live watch terminal. Sourced by ./lab and deploy/gcp/lab-gcp (they define ok and warn).
#   watch_open NAME BODY [force]
# Opens ONE graphical terminal that runs BODY (bash) and follows a build in real time.
# - No duplicate: the terminal writes its pid to logs/.watch-NAME.pid; a live pid means "already open".
# - Opt-out: LAB_WATCH=0 (ignored when force is given, for example by ./lab watch).
# - No graphical session or no terminal: print the command to run instead.
# - Terminal choice: $LAB_TERMINAL or $TERMINAL first, then common terminals (desktop-neutral).
watch_open() {
  local name=$1 body=$2 force=${3:-}
  [[ ${LAB_WATCH:-1} == 0 && -z $force ]] && return 0
  local dir="$LAB_ROOT/logs" pidf script t
  mkdir -p "$dir"
  pidf="$dir/.watch-$name.pid"
  script="$dir/.watch-$name.sh"
  touch "$LAB_ROOT/TRANSCRIPT.md"
  if [[ -f $pidf ]] && kill -0 "$(<"$pidf")" 2>/dev/null; then
    ok "watch terminal already open (pid $(<"$pidf"))"
    return 0
  fi
  cat >"$script" <<SCRIPT
#!/usr/bin/env bash
# generated by lib/watch.sh: live view of the lab build (close the window to stop)
echo \$\$ > '$pidf'
trap 'rm -f "$pidf"; kill 0 2>/dev/null' EXIT
cd '$LAB_ROOT' || exit 1
printf '\\e]0;lab watch: %s\\a' '$name'
$body
SCRIPT
  chmod +x "$script"
  if [[ -n ${DISPLAY:-}${WAYLAND_DISPLAY:-} ]]; then
    for t in "${LAB_TERMINAL:-}" "${TERMINAL:-}" xdg-terminal-exec x-terminal-emulator gnome-terminal konsole \
      xfce4-terminal ghostty kitty alacritty foot wezterm xterm; do
      if [[ -z $t ]] || ! type -P "${t%% *}" >/dev/null; then continue; fi
      case ${t##*/} in
        gnome-terminal) setsid "$t" --title="lab watch: $name" -- bash "$script" >/dev/null 2>&1 & ;;
        xdg-terminal-exec | kitty | foot | ghostty) setsid "$t" bash "$script" >/dev/null 2>&1 & ;;
        wezterm) setsid "$t" start -- bash "$script" >/dev/null 2>&1 & ;;
        konsole | xfce4-terminal) setsid "$t" -e "bash $script" >/dev/null 2>&1 & ;;
        *) setsid "$t" -e bash "$script" >/dev/null 2>&1 & ;;
      esac
      ok "watch terminal opened ($t); opt out with LAB_WATCH=0"
      return 0
    done
  fi
  warn "no graphical terminal: to watch live, run in a terminal: bash $script"
}

# Local builds: follow the progress log and the transcript.
watch_local() {
  local f=${PROGRESS_LOG:-$LAB_ROOT/logs/progress.log}
  mkdir -p "$(dirname "$f")"
  touch "$f"
  watch_open local "exec tail -n 100 -F '$f' TRANSCRIPT.md" "${1:-}"
}
